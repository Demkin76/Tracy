import {chromium,expect} from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
const root=path.resolve(".."),base="http://127.0.0.1:8000",out=path.join(root,"data","platform-presentation");
await fs.mkdir(out,{recursive:true});
const credentials=JSON.parse(await fs.readFile(path.join(root,"data/tracy-owner.json"),"utf8"));
const demo=JSON.parse(await fs.readFile(path.join(root,"data/platform-demo-report.json"),"utf8"));
const browser=await chromium.launch({channel:"chrome",headless:false});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on("pageerror",e=>errors.push(e.message));
try{
 await page.goto(base);
 await page.getByLabel("Email",{exact:true}).fill(credentials.email);
 await page.getByLabel("Password",{exact:true}).fill(credentials.password);
 await page.getByRole("button",{name:"Sign in",exact:true}).click();
 await page.getByRole("link",{name:"Explore agents",exact:true}).click();
 await expect(page.locator(".public-agent-card")).toHaveCount(2);
 await page.screenshot({path:path.join(out,"catalog-desktop.png"),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,"catalog-mobile.png"),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole("link",{name:"Atlas - Devnet payouts",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Atlas - Devnet payouts",exact:true})).toBeVisible();
 await page.screenshot({path:path.join(out,"atlas-profile.png"),fullPage:true});
 const receipt=demo.actions.find(a=>a.status==="VERIFIED").receipt_id;
 await page.goto(base+"/public/receipts/"+receipt);
 await page.getByRole("button",{name:"Verify public proof",exact:true}).click();
 await expect(page.locator(".verification-success")).toBeVisible({timeout:60000});
 await page.screenshot({path:path.join(out,"public-proof.png"),fullPage:true});
 const me=await(await context.request.get(base+"/v1/auth/me")).json();
 expect(me.user.email).toBe(credentials.email);
 const runtime=await(await context.request.get(base+"/v1/runtime")).json();
 expect(runtime.reconciler_enabled).toBe(true);
 expect(runtime.last_tick_at).toBeTruthy();
 expect(runtime.pending_actions).toBe(0);
 expect(errors).toEqual([]);
 await page.goto(base+"/explore");
 await fs.writeFile(path.join(out,"ready.json"),JSON.stringify({ready:true,public_agents:2,verified_receipt:receipt,runtime,browser_errors:errors},null,2));
 console.log("Tracy platform ready at "+base+"/explore");
}catch(e){console.error(e);await page.screenshot({path:path.join(out,"failure.png"),fullPage:true});await fs.writeFile(path.join(out,"ready.json"),JSON.stringify({ready:false,error:String(e),browser_errors:errors},null,2));}
await new Promise(resolve=>browser.on("disconnected",resolve));
